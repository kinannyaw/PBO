    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed

    // Mengambil data dari setiap input
    String nama = txtInputNama.getText().trim();
    String nim = txtInputNIM.getText().trim();
    String prodi = txtInputProdi.getText().trim();
    String jurusan = txtInputJurusan.getText().trim();
    String universitas = txtInputUniversitas.getText().trim();
    String angkatanText = txtInputAngkatan.getText().trim();
    String ipkText = txtInputIPK.getText().trim();

    // Menentukan kategori mahasiswa
    String kategori = "";

    if (rbReguler.isSelected()) {
        kategori = "Reguler";
    } else if (rbBeasiswa.isSelected()) {
        kategori = "Beasiswa";
    }

    String jenisBeasiswa = txtInputJenisBeasiswa.getText().trim();
    String nominalBeasiswaText =
            txtInputNominalBeasiswa.getText().trim();

    // Mengambil pilihan UKT
    String nominalUKT = cmbUKT.getSelectedItem().toString();

    // Validasi data wajib
    if (nama.isEmpty() || nim.isEmpty()
            || prodi.isEmpty() || jurusan.isEmpty()
            || universitas.isEmpty() || angkatanText.isEmpty()
            || ipkText.isEmpty() || kategori.isEmpty()
            || nominalUKT.equals("Pilih UKT...")) {

        JOptionPane.showMessageDialog(this,
                "Mohon lengkapi semua data mahasiswa!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validasi khusus kategori beasiswa
    if (kategori.equals("Beasiswa")
            && (jenisBeasiswa.isEmpty()
            || nominalBeasiswaText.isEmpty())) {

        JOptionPane.showMessageDialog(this,
                "Jenis dan nominal beasiswa wajib diisi!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int angkatan = Integer.parseInt(angkatanText);
        BigDecimal ipk = new BigDecimal(ipkText);

        // Validasi IPK
        if (ipk.compareTo(BigDecimal.ZERO) < 0
                || ipk.compareTo(new BigDecimal("4.00")) > 0) {

            JOptionPane.showMessageDialog(this,
                    "IPK harus berada antara 0.00 sampai 4.00!");
            return;
        }

        BigDecimal nominalBeasiswa = null;

        if (kategori.equals("Beasiswa")) {
            nominalBeasiswa = new BigDecimal(nominalBeasiswaText);

            if (nominalBeasiswa.compareTo(BigDecimal.ZERO) < 0) {
                JOptionPane.showMessageDialog(this,
                        "Nominal beasiswa tidak boleh negatif!");
                return;
            }
        } else {
            jenisBeasiswa = null;
        }

        // Perintah SQL untuk menyimpan data
        String sql = "INSERT INTO mahasiswa "
                + "(nama, nim, program_studi, jurusan, universitas, "
                + "angkatan, ipk, kategori, jenis_beasiswa, "
                + "nominal_beasiswa, nominal_ukt) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        // Membuka koneksi database
        try (Connection conn = KoneksiDatabase.getConnection()) {

            if (conn == null) {
                JOptionPane.showMessageDialog(this,
                        "Koneksi database gagal!");
                return;
            }

            try (PreparedStatement pst = conn.prepareStatement(sql)) {

                pst.setString(1, nama);
                pst.setString(2, nim);
                pst.setString(3, prodi);
                pst.setString(4, jurusan);
                pst.setString(5, universitas);
                pst.setInt(6, angkatan);
                pst.setBigDecimal(7, ipk);
                pst.setString(8, kategori);
                pst.setString(9, jenisBeasiswa);

                if (nominalBeasiswa != null) {
                    pst.setBigDecimal(10, nominalBeasiswa);
                } else {
                    pst.setNull(10, java.sql.Types.DECIMAL);
                }

                pst.setString(11, nominalUKT);

                // Menyimpan data ke MySQL
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this,
                        "Data mahasiswa berhasil disimpan!",
                        "Berhasil",
                        JOptionPane.INFORMATION_MESSAGE);

                resetForm();
            }
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Angkatan, IPK, dan nominal beasiswa harus berupa angka!",
                "Kesalahan Input",
                JOptionPane.ERROR_MESSAGE);

    } catch (SQLException e) {

        if ("23000".equals(e.getSQLState())) {
            JOptionPane.showMessageDialog(this,
                    "NIM sudah terdaftar! Gunakan NIM lain.",
                    "Data Duplikat",
                    JOptionPane.WARNING_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Gagal menyimpan data: " + e.getMessage(),
                    "Kesalahan Database",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnSimpanActionPerformed
